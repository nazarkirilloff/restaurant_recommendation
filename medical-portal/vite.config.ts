import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { defineConfig, minifySync, type Plugin } from "vite";
import react from "@vitejs/plugin-react";
import { viteSingleFile } from "vite-plugin-singlefile";

/**
 * Content-Security-Policy for the built single-file page. It is what makes
 * "nothing leaves your browser" enforced rather than promised: no network
 * connections of any kind (fetch/XHR/WebSocket/beacons), no external images,
 * scripts, styles, fonts, frames, forms or <base>. Scripts are allowed only by
 * hash, the worker only as blob:, and Trusted Types block DOM injection.
 * (Top-level navigation can't be restricted by CSP; there is no code that does it.)
 */
function csp(scriptHashes: string[]): string {
  return [
    "default-src 'none'",
    `script-src ${scriptHashes.join(" ")}`,
    "style-src 'unsafe-inline'", // React/Recharts style attributes and the inlined stylesheet
    "img-src data: blob:",
    "font-src data:",
    "connect-src 'none'",
    "worker-src blob:",
    "frame-src 'none'",
    "object-src 'none'",
    "media-src 'none'",
    "manifest-src 'none'",
    "base-uri 'none'",
    "form-action 'none'",
    "require-trusted-types-for 'script'",
    "trusted-types default",
  ].join("; ");
}

/**
 * HTTP response headers for hosting the page (written to dist/_headers, the
 * format Netlify and Cloudflare Pages read; see README → Hosting for others).
 * The CSP repeats the meta tag and adds what only a header can do:
 * frame-ancestors (clickjacking). The rest close remaining browser side doors.
 */
export function securityHeaders(policy: string): Record<string, string> {
  return {
    "Content-Security-Policy": `${policy}; frame-ancestors 'none'`,
    "X-Frame-Options": "DENY",
    "Referrer-Policy": "no-referrer",
    "X-Content-Type-Options": "nosniff",
    "Cross-Origin-Opener-Policy": "same-origin",
    "Cross-Origin-Resource-Policy": "same-origin",
    "Strict-Transport-Security": "max-age=63072000; includeSubDomains",
    "Permissions-Policy":
      "camera=(), microphone=(), geolocation=(), payment=(), usb=(), serial=(), hid=(), midi=(), display-capture=(), clipboard-read=(), browsing-topics=()",
    // Results never leave the browser, but don't let caches keep stale builds around.
    "Cache-Control": "no-cache",
  };
}

/** After the single-file plugin has inlined everything, hash every inline script and add the CSP. */
function contentSecurityPolicy(): Plugin {
  let outDir = "dist";
  return {
    name: "content-security-policy",
    apply: "build",
    enforce: "post",
    configResolved(config) {
      outDir = config.build.outDir;
    },
    writeBundle() {
      const file = join(outDir, "index.html");
      // Minify what the bundler doesn't touch: the small inline head script and
      // the markup (comments, indentation). Done before hashing, so the CSP
      // hashes match the final bytes.
      // Only the <head> is touched: the bundle's own code (in <body>) is already
      // minified and contains "<script>" strings of its own.
      const raw = readFileSync(file, "utf8");
      const headEnd = raw.indexOf("</head>");
      if (headEnd < 0) throw new Error("CSP: </head> not found");
      const head = raw
        .slice(0, headEnd)
        .replace(/<script>([\s\S]*?)<\/script>/g, (_, code: string) => {
          const out = minifySync("inline.js", code);
          if (out.errors?.length) throw new Error(`minify inline script: ${out.errors[0].message}`);
          return `<script>${out.code.trim()}</script>`;
        })
        .replace(/<!--[\s\S]*?-->/g, "")
        .replace(/>\s+</g, "><");
      const html = head + raw.slice(headEnd);
      const hashes = [...html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/g)].map(
        (m) => `'sha256-${createHash("sha256").update(m[1]).digest("base64")}'`,
      );
      if (hashes.length === 0) throw new Error("CSP: no inline scripts found");
      const meta = `<meta http-equiv="Content-Security-Policy" content="${csp(hashes)}" />`;
      const charset = /<meta charset="UTF-8"\s*\/?>/i;
      if (!charset.test(html)) throw new Error("CSP: <meta charset> not found");
      writeFileSync(file, html.replace(charset, (m) => `${m}${meta}`));
      const headers = Object.entries(securityHeaders(csp(hashes)))
        .map(([k, v]) => `  ${k}: ${v}`)
        .join("\n");
      writeFileSync(join(outDir, "_headers"), `# Generated by the build; scripts/check-headers.mjs verifies a deployment.\n/*\n${headers}\n`);
    },
  };
}

export default defineConfig({
  plugins: [react(), viteSingleFile(), contentSecurityPolicy()],
  server: {
    port: 5173,
    // Localhost only: never expose the dev server (and the project folder) to the network.
    host: "127.0.0.1",
    strictPort: true,
  },
  build: {
    assetsInlineLimit: 100_000_000,
    cssCodeSplit: false,
    // No <link rel="modulepreload"> exists in a single file; drop the fetch()-based polyfill.
    modulePreload: false,
    // (vite-plugin-singlefile turns code splitting off, so everything lands in one file.)
  },
});
